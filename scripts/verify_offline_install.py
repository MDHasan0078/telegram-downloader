#!/usr/bin/env python3
"""Prove the hermetic offline install still works on every supported Python.

This is the check that matters most. The repo shipped a .deb that hard-failed
on first launch under Python 3.10 because `exceptiongroup` was missing from
wheels/ and the lockfile (anyio needs it on <3.11), and vendoring msgpack as a
single pure-python wheel rewrote all of wheels/. Either could silently
reintroduce that class of bug, because reading the lockfile by eye cannot tell
you what a given interpreter will actually resolve: `python_version < "3.11"`
is False at 3.12, which is exactly how the gap hid.

So resolve it the way the package does, per interpreter, and fail loudly.

    scripts/verify_offline_install.py [--json]

Exit code 0 if every available interpreter installs offline, 1 otherwise.
Interpreters that are not installed are reported as SKIPPED, not failed: an
absent interpreter says nothing about the package.
"""
from __future__ import annotations

import argparse
import json
import os
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
WHEELS = REPO / "wheels"
LOCK = REPO / "requirements-runtime.lock"

# requires-python is >=3.10 (pyproject.toml). Where a real interpreter for each
# version may live: a uv-installed build in ~/.local/bin, or the system one.
CANDIDATES = {
    "3.10": ["/root/.local/bin/python3.10", "/usr/bin/python3.10"],
    "3.11": ["/root/.local/bin/python3.11", "/usr/bin/python3.11"],
    "3.12": [str(REPO / ".venv/bin/python"), "/usr/bin/python3.12"],
    "3.13": ["/root/.local/bin/python3.13", "/usr/bin/python3.13"],
    "3.14": ["/root/.local/bin/python3.14", "/usr/bin/python3.14"],
}


def find(paths: list[str]) -> str | None:
    for p in paths:
        if os.path.exists(p):
            return p
    return None


def check(version: str, interpreter: str) -> dict:
    """Install requirements-runtime.lock offline into a throwaway venv."""
    venv = tempfile.mkdtemp(prefix=f"venv{version}-")
    try:
        made = subprocess.run([interpreter, "-m", "venv", venv],
                              capture_output=True, text=True)
        if made.returncode != 0:
            # e.g. this interpreter lacks ensurepip. Environmental, and says
            # nothing about the package -- skip, do not fail.
            return {"version": version, "status": "skipped",
                    "detail": "cannot create a venv with this interpreter"}

        pip = os.path.join(venv, "bin", "pip")
        # Only the committed lockfile. requirements-project.lock is GENERATED by
        # build-deb.sh at build time (it pins the freshly-built project wheel),
        # so it does not exist in a checkout -- passing it here is a bug in the
        # checker, not a problem with the package.
        proc = subprocess.run(
            [pip, "install", "--no-index", "--find-links", str(WHEELS),
             "--require-hashes", "--only-binary", ":all:",
             "--no-build-isolation", "--no-cache-dir", "-r", str(LOCK)],
            capture_output=True, text=True)
        if proc.returncode != 0:
            tail = [ln for ln in (proc.stderr or "").strip().splitlines()
                    if ln.strip()][-4:]
            return {"version": version, "status": "fail",
                    "detail": f"exit {proc.returncode}: " + " | ".join(tail)}

        names = subprocess.run([os.path.join(venv, "bin", "pip"), "freeze"],
                               capture_output=True, text=True).stdout.split()
        return {"version": version, "status": "pass",
                "detail": f"{len(names)} packages"}
    except Exception as exc:  # noqa: BLE001 - report, never crash the run
        return {"version": version, "status": "error",
                "detail": f"{type(exc).__name__}: {exc}"}
    finally:
        shutil.rmtree(venv, ignore_errors=True)


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--json", action="store_true", help="machine-readable output")
    args = ap.parse_args()

    if not WHEELS.is_dir() or not LOCK.is_file():
        print(f"missing {WHEELS} or {LOCK}; run from inside the repo",
              file=sys.stderr)
        return 1

    if not args.json:
        print("exact command from build-deb.sh run.sh:")
        print("  pip install --no-index --find-links wheels --require-hashes")
        print("        --only-binary :all: --no-build-isolation --no-cache-dir")
        print("        -r requirements-runtime.lock")
        print()

    results, failed = [], []
    for version, paths in CANDIDATES.items():
        interpreter = find(paths)
        if interpreter is None:
            r = {"version": version, "status": "skipped",
                 "detail": "no interpreter available"}
        else:
            r = check(version, interpreter)
        results.append(r)
        if not args.json:
            print(f"  {r['version']}: {r['status'].upper()}  ({r['detail']})")
        if r["status"] in ("fail", "error"):
            failed.append(r["version"])

    if args.json:
        print(json.dumps({"results": results, "failed": failed}, indent=2))
    else:
        print()
        if failed:
            print("VERDICT: FAIL on", ", ".join(failed))
        else:
            print("VERDICT: PASS - every available Python installs offline.")
    return 1 if failed else 0


if __name__ == "__main__":
    sys.exit(main())