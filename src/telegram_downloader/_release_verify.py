# --------------------------------------------------------------------------
# PINNED TRUST ANCHOR — CURRENTLY EMPTY. READ THIS.
# --------------------------------------------------------------------------
#
# >>> THIS MUST BE FILLED IN BEFORE THE IN-APP UPDATER CAN INSTALL ANYTHING. <<<
#
# With an empty keyring every manifest is refused (`NoPinnedSigningKeyError`),
# so `download_asset()` raises instead of publishing an unverified installer.
# That is deliberate: a keyring that silently accepts an unconfigured signer is
# exactly the self-assertion bug this module was written to remove. The fix is
# a real key, NOT an "unsigned releases are fine" flag.
#
# OPERATOR CHECKLIST (in order; nothing here needs to happen twice)
#
#   1. Create the release key ONCE, offline, and keep an encrypted/offline
#      backup of it. It is never generated by CI and never committed:
#
#          umask 077
#          openssl genpkey -algorithm ed25519 -out release-signing.key
#
#   2. Print the raw 32-byte public key and base64 it (an SPKI DER blob for
#      Ed25519 is exactly 44 bytes: 12-byte header + the 32 raw key bytes):
#
#          openssl pkey -in release-signing.key -pubout -outform DER | tail -c 32 \
#              | base64 -w0
#
#   3. Store the PRIVATE key as a repository secret, base64 of the PEM:
#
#          base64 -w0 release-signing.key     # -> secret RELEASE_SIGNING_KEY
#
#      The `release` job in .github/workflows/build.yml reads ONLY that secret
#      (never a file from the repo), writes it to $RUNNER_TEMP under `umask
#      077`, and deletes it on exit via an EXIT trap. Fork PRs see an empty
#      secret and publish unsigned manifests, which the app then refuses —
#      that is the correct outcome, not a bug to work around.
#
#   4. Paste the PUBLIC key from step 2 into the dict below, keeping a
#      descriptive label:
#
#          "ed25519:2026-01": "<base64 of the 32 raw bytes>",
#
#      Keep retired keys listed for as long as old releases must still
#      verify, then remove them.
#
#   5. Sanity-check without shipping anything:
#
#          python -c "from telegram_downloader import _release_verify as rv; \
#              print(rv.validate_pinned_keys().summary)"
#
#      It must print ok=True. While the dict is empty it prints ok=False and
#      says exactly what is missing — that string is what the GUI/CLI shows
#      when an install is refused, so a broken keyring is diagnosable instead
#      of mysterious.
#
# Format: {key_id: base64(32 raw little-endian Ed25519 public key bytes)}.
# The dict is only a lookup table — EVERY configured key is tried and the one
# that verifies is reported, so there is no "claimed" id an attacker can lie
# about to steer verification. Key ids are advisory labels for humans and
# error messages; the machine-readable id inside the .sig envelope is
# `key_id_for()` = first 8 hex of SHA-256(b"tgdl-release-key:" + pubkey).
#
# ---------------------------------------------------------------------------
# CI: producing the signed releases — IMPLEMENTED in .github/workflows/build.yml
# ---------------------------------------------------------------------------
# The `release` job signs the three manifests and attaches
# SHA256SUMS-{deb,apk,dmg}.sig next to them. The commands, so the two files can
# be diffed against each other if the format ever changes:
#
#   umask 077
#   printf '%s' "$RELEASE_SIGNING_KEY" | base64 -d > "$RUNNER_TEMP/key.pem"
#   # KEYID = first 8 hex of SHA-256(b"tgdl-release-key:" + raw pubkey)
#   openssl pkeyutl -sign -inkey "$RUNNER_TEMP/key.pem" -rawin \
#     -in deb/SHA256SUMS-deb -out "$RUNNER_TEMP/SHA256SUMS-deb.sig.raw"
#   printf 'tgdl-ed25519-v1 %s %s\n' "$KEYID" \
#     "$(base64 -w0 < "$RUNNER_TEMP/SHA256SUMS-deb.sig.raw")" \
#     > deb/SHA256SUMS-deb.sig
#
# `-rawin` is required and is not optional sugar: Ed25519 signs the message
# itself (PureEdDSA), so OpenSSL refuses without it and, with it, the 64 output
# bytes are exactly what `parse_signature_blob()` and `_verify_raw()` consume.
# The base64 payload of the envelope must decode to exactly 64 bytes and the
# key id to exactly 8 lowercase hex characters; CI asserts both before it
# attaches anything, so a malformed envelope fails the release instead of
# shipping a manifest every client will reject.
#
# NOTE on `gpg --detach-sign`: GPG is a fine signing tool, but its output is an
# OpenPGP *packet* — accepting one would mean shipping an OpenPGP parser (or
# shelling out to gpg from inside the verification path, which is a dependency
# and a subprocess attack surface). CI no longer publishes the old
# SHA256SUMS-<plat>.asc manifests, and `_release_verify.py` never reads them.
# If GPG is preferred for some other artifact, pin that key's fingerprint
# instead and do not add a permissive OpenPGP parser here.
