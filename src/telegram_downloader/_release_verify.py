# Asset suffix of the detached Ed25519 signature next to each manifest:
#   SHA256SUMS-deb      (signed document)
#   SHA256SUMS-deb.sig  (detached Ed25519 signature over it)
SIGNATURE_SUFFIX = ".sig"

# Envelope used by CI so an unverifiable signature can be attributed:
#     tgdl-ed25519-v1 <8-hex key id> <base64 of the 64 raw signature bytes>
# Exactly one line, ASCII, trailing newline: "<prefix> <keyid> <base64>\n".
# The key id is derived from the PUBLIC key (see key_id_for), never from the
# signature, and is only a lookup hint: a wrong id fails closed, it can never
# make an unverified signature pass.
SIGNATURE_ENVELOPE_PREFIX = "tgdl-ed25519-v1"
_KEY_ID_RE = re.compile(r"^[0-9a-f]{8}$")


MAX_MANIFEST_BYTES = 64 * 1024
MAX_SIGNATURE_BYTES = 1024  # raw 64B, or a small ASCII envelope


class MissingSignatureError(Exception):
    """The release published no detached signature for the manifest."""


class UnknownSigningKeyError(Exception):
    """A signature is present but matches none of the pinned public keys."""


class NoPinnedSigningKeyError(Exception):
    """No release signing key is pinned, so nothing can be trusted."""


class SignatureFormatError(Exception):
    """The signature blob is not a well-formed 64-byte Ed25519 signature."""


class BadSignatureError(Exception):
    """The signature does not verify against the manifest bytes."""


# --------------------------------------------------------------------------
# Pure-Python Ed25519 (RFC 8032) — verify only.
# --------------------------------------------------------------------------
_P = 2 ** 255 - 19
_Q = 2 ** 252 + 27742317777372353535851937790883648493
_D = (-121665 * pow(121666, _P - 2, _P)) % _P
_I = pow(2, (_P - 1) // 4, _P)


def _sha512(data: bytes) -> bytes:
    return hashlib.sha512(data).digest()


def _inv(x: int) -> int:
    return pow(x, _P - 2, _P)


def _x_recover(y: int) -> int:
    xx = (y * y - 1) * _inv(_D * y * y + 1) % _P
    x = pow(xx, (_P + 3) // 8, _P)
    if (x * x - xx) % _P != 0:
        x = x * _I % _P
    if x % 2 != 0:
        x = _P - x
    return x


_BY = 4 * _inv(5) % _P
_BX = _x_recover(_BY)
_B = (_BX % _P, _BY % _P, 1, _BX * _BY % _P)
_IDENT = (0, 1, 1, 0)
_SIGNATURE_LEN = 64
_PUBLIC_KEY_LEN = 32


def _point_add(p: tuple[int, int, int, int],
               q: tuple[int, int, int, int]) -> tuple[int, int, int, int]:
    """Extended-homogeneous coordinates (X:Y:Z:T) addition on edwards25519."""
    a = (p[1] - p[0]) * (q[1] - q[0]) % _P
    b = (p[1] + p[0]) * (q[1] + q[0]) % _P
    c = 2 * p[3] * q[3] * _D % _P
    dd = 2 * p[2] * q[2] % _P
    e, f, g, h = b - a, dd - c, dd + c, b + a
    return (e * f % _P, g * h % _P, f * g % _P, e * h % _P)


def _scalar_mult(point: tuple[int, int, int, int],
                 scalar: int) -> tuple[int, int, int, int]:
    result = _IDENT
    while scalar > 0:
        if scalar & 1:
            result = _point_add(result, point)
        point = _point_add(point, point)
        scalar >>= 1
    return result


def _point_equal(p: tuple[int, int, int, int],
                 q: tuple[int, int, int, int]) -> bool:
    if (p[0] * q[2] - q[0] * p[2]) % _P != 0:
        return False
    if (p[1] * q[2] - q[1] * p[2]) % _P != 0:
        return False
    return True


def _is_prime_order(point: tuple[int, int, int, int]) -> bool:
    """True iff *point* lies in the prime-order subgroup of edwards25519.

    The full curve group is Z_L x Z_8 (L prime, cofactor 8), so the curve holds
    eight cosets of "normal" points, and the Z_8 factor consists of small-order
    points that are *on the curve* — `_is_on_curve()` accepts them. Pinning one
    is catastrophic and completely silent: for such a key the RFC 8032 check

        [S]B == R + [k]A

    collapses to `identity == identity` for every message, because the attacker
    picks R = -[k]A and S = 0 and needs no private key at all. That is exactly
    why the subgroup test is mandatory here and not merely "belt and braces".

    L is prime, so `[L]P == identity` places P in the L-torsion (which is the
    prime-order subgroup); excluding the identity then forces order(P) == L.
    Cost is one extra scalar multiplication per point — acceptable, since a
    verification happens once per release check, not per byte.
    """
    if _point_equal(point, _IDENT):
        return False
    return _point_equal(_scalar_mult(point, _Q), _IDENT)


def _point_decompress(data: bytes) -> tuple[int, int, int, int] | None:
    """Decode a compressed point, or None when it is not one we will use.

    Rejects, in order: wrong length; non-canonical `y >= p` (the classic
    signature-malleability vector); points that are not on the curve; and
    points outside the prime-order subgroup (low-order / torsion points,
    including the identity).

    Both the public key A and R are decoded through this function on purpose,
    so no caller can forget the subgroup check: a torsion R is the other half
    of the degenerate-key forgery above, and a torsion A is the key half.
    """
    if len(data) != 32:
        return None
    encoded = int.from_bytes(data, "little")
    sign = encoded >> 255
    y = encoded & ((1 << 255) - 1)
    if y >= _P:  # non-canonical y encoding (allows signature malleability)
        return None
    x = _x_recover(y)
    if x & 1 != sign:
        x = _P - x
    point = (x, y, 1, x * y % _P)
    if not _is_on_curve(point):
        return None
    if not _is_prime_order(point):
        return None
    return point


def _is_on_curve(point: tuple[int, int, int, int]) -> bool:
    x, y, z, t = point
    return (
        (-x * x + y * y - z * z - _D * t * t) % _P == 0
        and (x * y % _P) == (z * t % _P)
    )


def _verify_raw(public_key: bytes, signature: bytes, message: bytes) -> bool:
    """RFC 8032 §5.1.7 verification. Returns False for every malformed input."""
    if len(public_key) != _PUBLIC_KEY_LEN or len(signature) != _SIGNATURE_LEN:
        return False
    a_point = _point_decompress(public_key)
    if a_point is None:
        return False
    r_bytes = signature[:32]
    s = int.from_bytes(signature[32:], "little")
    if s >= _Q:  # non-canonical / malleable S: reject outright
        return False
    r_point = _point_decompress(r_bytes)
    if r_point is None:
        return False
    k = int.from_bytes(_sha512(r_bytes + public_key + message), "little") % _Q
    # [S]B == R + [k]A
    left = _scalar_mult(_B, s)
    right = _point_add(r_point, _scalar_mult(a_point, k))
    return _point_equal(left, right)


