def key_id_for(public_key: bytes) -> str:
    """Short stable label for a public key (first 4 bytes of SHA-256)."""
    return hashlib.sha256(b"tgdl-release-key:" + public_key).hexdigest()[:8]


def decode_public_key(encoded: str, *, require_usable: bool = False) -> bytes:
    """base64 -> 32 raw bytes, with strict validation.

    With `require_usable=True` the bytes must also be a *usable* Ed25519 public
    key: canonical encoding, on the curve, and in the prime-order subgroup. A
    low-order (torsion) key is rejected here on purpose — see
    `_is_prime_order()` — because pinning one would let anyone forge a
    manifest. The verification path calls this with `require_usable=False` so
    it can *report* a broken pin as an unusable signer instead of aborting the
    whole call on the first bad entry; `_verify_raw()` re-applies the check
    regardless, so nothing slips through that route.
    """
    if not isinstance(encoded, str) or not encoded:
        raise SignatureFormatError("Pinned key is not a string.")
    try:
        raw = base64.b64decode(encoded.encode("ascii"), validate=True)
    except Exception as exc:
        raise SignatureFormatError("Pinned key is not valid base64.") from exc
    if len(raw) != _PUBLIC_KEY_LEN:
        raise SignatureFormatError(
            f"Pinned key must be 32 raw bytes, got {len(raw)}.")
    if require_usable and _point_decompress(raw) is None:
        raise SignatureFormatError(
            "Pinned key is not a usable Ed25519 public key: it is not a "
            "canonical point of the prime-order subgroup (an off-curve, "
            "non-canonical or low-order/torsion point). Such a key makes "
            "verification meaningless, so it is refused.")
    return raw


def _is_valid_b64_key(encoded: str) -> bool:
    """True when *encoded* is a structurally AND algebraically usable key."""
    try:
        decode_public_key(encoded, require_usable=True)
    except Exception:
        return False
    return True


def _key_problem(encoded: str) -> str | None:
    """One short reason string for an unusable pin, or None if it is fine."""
    try:
        decode_public_key(encoded, require_usable=True)
    except SignatureFormatError as exc:
        return str(exc)
    except Exception:
        return "Pinned key could not be decoded."
    return None


class PinnedKeyStatus(NamedTuple):
    """Diagnostic view of the trust anchor (see `validate_pinned_keys`)."""

    ok: bool                     # at least one usable key is pinned
    summary: str                  # one-line human-readable state
    key_ids: list[str]            # "<label> (id xxxxxxxx)" per usable key
    problems: list[str]           # one line per unusable key / misconfiguration


def validate_pinned_keys(keyring: dict[str, str] | None = None) -> PinnedKeyStatus:
    """Diagnose the trust anchor without attempting any verification.

    Returns whether the keyring can actually verify a release, a one-line
    summary suitable for an error message or a status panel, the ids of the
    usable keys, and a list of specific problems. The CLI/GUI can call this so
    a misconfigured keyring is diagnosable instead of mysterious — it is the
    same information `keyring_state()` renders, without the string soup.
    """
    ring = PINNED_RELEASE_SIGNING_KEYS if keyring is None else keyring
    key_ids: list[str] = []
    problems: list[str] = []
    seen_ids: dict[str, str] = {}

    for label in sorted(ring):
        encoded = ring[label]
        reason = _key_problem(encoded)
        if reason is not None:
            problems.append(f"{label}: unusable pinned key — {reason}")
            continue
        key_id = key_id_for(decode_public_key(encoded))
        if key_id in seen_ids:
            problems.append(
                f"{label}: duplicate key (same public key as "
                f"{seen_ids[key_id]!r}); removing one entry would not weaken "
                "anything")
            continue
        seen_ids[key_id] = label
        key_ids.append(f"{label} (id {key_id})")

    if not ring:
        summary = (
            "NO release signing key is pinned in "
            "telegram_downloader/_release_verify.py — generate one with "
            "`openssl genpkey -algorithm ed25519`, store it as the "
            "RELEASE_SIGNING_KEY repository secret and pin its public key in "
            "PINNED_RELEASE_SIGNING_KEYS (see the operator checklist in that "
            "module). Unsigned/unverifiable releases are refused on purpose.")
    elif not key_ids:
        summary = (
            f"{len(ring)} release signing key(s) are pinned in "
            "telegram_downloader/_release_verify.py but NONE is usable "
            f"({problems[0] if problems else 'unknown reason'}); unsigned and "
            "unverifiable releases are refused on purpose.")
    elif problems:
        summary = (
            "Pinned release signing keys: "
            + ", ".join(key_ids)
            + f" (WARNING: {len(problems)} pinned key(s) rejected — "
            + "; ".join(problems) + ")")
    else:
        summary = "Pinned release signing keys: " + ", ".join(key_ids)

    return PinnedKeyStatus(ok=bool(key_ids), summary=summary,
                           key_ids=key_ids, problems=problems)


def pinned_key_ids() -> list[str]:
    """Configured key ids, without exposing the keys themselves.

    Entries that cannot be used are labelled as such rather than hidden.
    """
    return validate_pinned_keys().key_ids


def keyring_state() -> str:
    """Human-readable state of the trust anchor, for error messages/logs."""
    return validate_pinned_keys().summary


def parse_signature_blob(blob: bytes) -> tuple[str | None, bytes]:
    """Return (key_id_or_None, 64 raw signature bytes).

    Two accepted forms, both strict:
      * the envelope CI publishes:
            tgdl-ed25519-v1 <8-hex key id> <base64 signature>
      * the bare 64 raw signature bytes (no key id).

    No guessing at other armoured/hex/pem forms: a permissive parser here is
    exactly where a signature we did not intend to read could sneak in.
    """
    if not isinstance(blob, (bytes, bytearray)):
        raise SignatureFormatError("Signature is not bytes.")
    blob = bytes(blob)
    if len(blob) > MAX_SIGNATURE_BYTES:
        raise SignatureFormatError("Signature blob too large.")
    if len(blob) == _SIGNATURE_LEN:
        return None, blob
    try:
        text = blob.decode("ascii").strip()
    except UnicodeDecodeError as exc:
        raise SignatureFormatError(
            f"Expected a raw {_SIGNATURE_LEN}-byte Ed25519 signature or the "
            f"{SIGNATURE_ENVELOPE_PREFIX} envelope.") from exc
    parts = text.split()
    if len(parts) != 3 or parts[0] != SIGNATURE_ENVELOPE_PREFIX:
        raise SignatureFormatError(
            f"Expected a raw {_SIGNATURE_LEN}-byte Ed25519 signature or a "
            f"'{SIGNATURE_ENVELOPE_PREFIX} <key-id> <base64>' envelope.")
    if not _KEY_ID_RE.match(parts[1]):
        raise SignatureFormatError(f"Bad signature key id: {parts[1]!r}")
    try:
        raw = base64.b64decode(parts[2].encode("ascii"), validate=True)
    except Exception as exc:
        raise SignatureFormatError("Signature is not valid base64.") from exc
    if len(raw) != _SIGNATURE_LEN:
        raise SignatureFormatError(
            f"Expected a {_SIGNATURE_LEN}-byte signature, got {len(raw)}.")
    return parts[1], raw


def verify_manifest_signature(manifest: bytes, signature: bytes | None,
                              keys: dict[str, str] | None = None) -> str:
    """Verify *manifest* against a detached Ed25519 *signature*.

    Returns the label of the key that verified. Raises (never returns a
    "close enough") on every failure path:

        MissingSignatureError    signature is None/absent
        NoPinnedSigningKeyError  no key at all is pinned in this build
        SignatureFormatError     signature blob is malformed
        UnknownSigningKeyError   signed by a key this build does not pin
        BadSignatureError        signature does not verify for this manifest

    EVERY pinned key is tried, in sorted order, and the one that verifies is
    what gets reported. The key id inside the `tgdl-ed25519-v1` envelope is an
    attribution hint only: it reorders the candidates, it never limits them,
    and an id that names nothing pinned is refused outright. Pinning several
    keys (old + new, during a rotation) therefore keeps working when the
    envelope id is wrong, which the "try only the claimed id" behaviour used
    to get wrong.

    A pin that is not a usable public key (off-curve, non-canonical, or a
    low-order/torsion point) is skipped rather than trusted, and named in the
    resulting error so a broken keyring stays diagnosable. It never makes the
    call succeed: with every pin unusable, verification simply always fails.
    The exception class still follows the candidate count (one pin => tampered
    signature; several => unknown signer), which is what callers report to
    users; `keyring_state()` / `validate_pinned_keys()` carry the diagnosis.
    """
    if signature is None:
        raise MissingSignatureError(
            "This release is not signed (no detached Ed25519 signature "
            f"published). {keyring_state()} Signed releases only are "
            "accepted; pass an explicit opt-in to allow unsigned releases.")
    if not isinstance(manifest, (bytes, bytearray)):
        raise SignatureFormatError("Manifest is not bytes.")
    manifest = bytes(manifest)
    if len(manifest) > MAX_MANIFEST_BYTES:
        raise SignatureFormatError("Manifest too large to verify.")

    keyring = PINNED_RELEASE_SIGNING_KEYS if keys is None else keys
    if not keyring:
        raise NoPinnedSigningKeyError(
            "No release signing key is pinned in this build, so the release "
            "cannot be trusted. This is a build/config problem, not a "
            "reason to fall back to an unsigned installer. See "
            "telegram_downloader/_release_verify.py for the operator "
            "checklist.")

    claimed_id, sig = parse_signature_blob(signature)

    # Only usable keys get an id and a verification attempt; an unusable one is
    # reported as such rather than trusted or silently fatal.
    by_id: dict[str, str] = {}
    unusable: list[str] = []
    usable_labels: set[str] = set()
    for label in sorted(keyring):
        problem = _key_problem(keyring[label])
        if problem is not None:
            unusable.append(f"{label} ({problem})")
            continue
        usable_labels.add(label)
        by_id.setdefault(key_id_for(decode_public_key(keyring[label])), label)

    if claimed_id is not None and claimed_id not in by_id:
        raise UnknownSigningKeyError(
            f"Release is signed by key id {claimed_id}, which is NOT pinned "
            f"in this build (pinned: {', '.join(sorted(by_id)) or 'none'}). "
            "Refusing: an unknown signer is not a trust anchor."
            + _unusable_note(unusable))

    # Try the claimed key first (nicer error attribution), then every other
    # pin: the id is a hint, never a filter.
    candidates = ([by_id[claimed_id]] if claimed_id in by_id else [])
    candidates += [label for label in sorted(keyring) if label not in candidates]

    for label in candidates:
        if label not in usable_labels:
            continue
        if _verify_raw(decode_public_key(keyring[label]), sig, manifest):
            return label

    if claimed_id is not None:
        # Known key, signature simply does not verify => tampered manifest.
        raise BadSignatureError(
            "Release manifest does not match its signature (the manifest or "
            "the installer digests in it were modified); refusing."
            + _unusable_note(unusable))
    if len(candidates) == 1:
        raise BadSignatureError(
            "Release manifest does not match its signature from the single "
            f"pinned key {candidates[0]!r}; refusing."
            + _unusable_note(unusable))
    raise UnknownSigningKeyError(
        "Release is signed by a key that is NOT pinned in this build "
        f"(tried {len(candidates)} key(s): {', '.join(candidates)}). "
        "Refusing: an unknown signer is not a trust anchor."
        + _unusable_note(unusable))


def _unusable_note(unusable: list[str]) -> str:
    """Append an explanation of rejected pins to an error message."""
    if not unusable:
        return ""
    return (" Note: pinned key(s) rejected as unusable and therefore not "
            "tried: " + "; ".join(unusable) + ".")
